export const CATALOG = [...STARS, ...PLANETS, ...DEEP_SKY];

const byId = new Map(CATALOG.map((o) => [o.id, o]));

export function getObject(id) {
  return byId.get(id) || null;
}

export function getPlanets(hostId) {
  const host = byId.get(hostId);
  if (!host || !host.planets) return [];
  return host.planets.map((id) => byId.get(id)).filter(Boolean);
}

export function getHost(planet) {
  return planet && planet.host ? byId.get(planet.host) : null;
}

export function searchCatalog(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [];
  return CATALOG.map((o) => {
    const names = [o.name, o.id, ...(o.aliases || [])].map((s) => s.toLowerCase());
    let score = 99;
    for (const n of names) {
      if (n === q) score = Math.min(score, 0);
      else if (n.startsWith(q)) score = Math.min(score, 1);
      else if (n.includes(q)) score = Math.min(score, 2);
    }
    return { o, score };
  })
    .filter((x) => x.score < 99)
    .sort((a, b) => a.score - b.score || a.o.name.localeCompare(b.o.name))
    .map((x) => x.o);
}

export function catalogGroups() {
  return {
    stars: STARS,
    exoplanets: PLANETS,
    deepSky: DEEP_SKY,
  };
}

